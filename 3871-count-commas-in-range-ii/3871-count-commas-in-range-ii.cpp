class Solution {
public:
    long long countCommas(long long n) {
        if (n < 1000)
            return 0;

        if (n <= 999999) {
            return n - 999;
        }

        if (n <= 999999999) {
            return (999999 - 1000 + 1)
                 + 2 * (n - 1000000 + 1);
        }

        if (n <= 999999999999LL) {
            return (999999 - 1000 + 1)
                 + 2 * (999999999 - 1000000 + 1)
                 + 3 * (n - 1000000000LL + 1);
        }

        if (n <= 999999999999999LL) {
            return (999999 - 1000 + 1)
                 + 2 * (999999999 - 1000000 + 1)
                 + 3 * (999999999999LL - 1000000000LL + 1)
                 + 4 * (n - 1000000000000LL + 1);
        }

        if (n <= 1000000000000000LL) {
            return (999999 - 1000 + 1)
                 + 2 * (999999999 - 1000000 + 1)
                 + 3 * (999999999999LL - 1000000000LL + 1)
                 + 4 * (999999999999999LL - 1000000000000LL + 1)
                 + 5 * (n - 1000000000000000LL + 1);
        }

        return -1;
    }
};